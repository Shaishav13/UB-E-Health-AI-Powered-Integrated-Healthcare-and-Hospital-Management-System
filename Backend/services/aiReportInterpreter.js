/**
 * Generates lifestyle recommendations based on results
 */
function generateRecommendations(parameters, testType, highCount, lowCount, criticalCount) {
  const recommendations = [];
  
  // Critical values - immediate action
  if (criticalCount > 0) {
    recommendations.push({
      priority: "URGENT",
      icon: "⚠️",
      title: "Seek Immediate Medical Attention",
      description: "Your results show critical values that require prompt evaluation by a healthcare provider. Please contact your doctor immediately or visit an emergency facility."
    });
  }
  
  // Analyze specific parameters for targeted advice
  parameters.forEach(param => {
    if (param.status === "High" || param.status === "Low") {
      const advice = getParameterAdvice(param.name, param.status);
      if (advice && !recommendations.find(r => r.title === advice.title)) {
        recommendations.push(advice);
      }
    }
  });
  
  // General recommendations
  if (highCount > 0 || lowCount > 0) {
    recommendations.push({
      priority: "Important",
      icon: "📋",
      title: "Schedule a Follow-up Appointment",
      description: "Discuss these results with your doctor to understand what they mean for your health and what steps to take next."
    });
  }
  
  // Always include general wellness advice
  recommendations.push({
    priority: "General",
    icon: "💪",
    title: "Maintain Healthy Lifestyle Habits",
    description: "Continue or adopt healthy habits: balanced diet, regular exercise, adequate sleep (7-9 hours), stress management, and staying hydrated."
  });
  
  return recommendations;
}

