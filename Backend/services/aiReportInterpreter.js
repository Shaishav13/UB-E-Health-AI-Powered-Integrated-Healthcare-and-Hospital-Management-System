/**
 * Generates relevant questions patient should ask their doctor
 */
function generateDoctorQuestions(parameters, testType) {
  const questions = [];
  
  // Check for abnormal values
  const abnormalParams = parameters.filter(p => p.status !== "Normal");
  
  if (abnormalParams.length > 0) {
    questions.push(`What do my abnormal ${testType} results mean for my overall health?`);
    questions.push(`Do I need any additional tests or follow-up appointments?`);
    questions.push(`Are there specific lifestyle changes or treatments you recommend based on these results?`);
  } else {
    questions.push(`How often should I repeat this ${testType} test?`);
    questions.push(`Are there any preventive measures I should take to maintain these healthy levels?`);
    questions.push(`Should I be monitoring any specific symptoms at home?`);
  }
  
  // Add parameter-specific questions
  abnormalParams.slice(0, 2).forEach(param => {
    const specificQuestion = getParameterQuestion(param.name, param.status);
    if (specificQuestion) {
      questions.push(specificQuestion);
    }
  });
  
  return questions.slice(0, 5); // Limit to 5 questions
}

