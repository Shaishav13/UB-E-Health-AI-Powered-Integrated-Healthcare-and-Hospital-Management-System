/**
 * Interprets lab report results and generates patient-friendly summary
 * @param {Object} labReport - The lab report object with results
 * @returns {Object} Structured interpretation with sections
 */
function interpretLabReport(labReport) {
  const { results, testType, testName, status } = labReport;
  
  if (!results || !results.parameters || results.parameters.length === 0) {
    return {
      error: "No results available to interpret",
      message: "This report does not contain test results yet."
    };
  }

  // Analyze parameters
  const normalCount = results.parameters.filter(p => p.status === "Normal").length;
  const highCount = results.parameters.filter(p => p.status === "High").length;
  const lowCount = results.parameters.filter(p => p.status === "Low").length;
  const criticalCount = results.parameters.filter(p => p.status === "Critical").length;
  const totalCount = results.parameters.length;

  // Generate executive summary
  const executiveSummary = generateExecutiveSummary(
    testName,
    normalCount,
    highCount,
    lowCount,
    criticalCount,
    totalCount
  );

  // Explain each parameter
  const parametersExplained = results.parameters.map(param => 
    explainParameter(param, testType)
  );

  // Generate recommendations
  const recommendations = generateRecommendations(
    results.parameters,
    testType,
    highCount,
    lowCount,
    criticalCount
  );

  // Generate questions for doctor
  const questionsForDoctor = generateDoctorQuestions(
    results.parameters,
    testType
  );

  return {
    executiveSummary,
    parametersExplained,
    recommendations,
    questionsForDoctor,
    technicalSummary: results.summary,
    technicalRemarks: results.remarks,
    disclaimer: "This summary is generated by AI for educational purposes only. Please consult your physician before making any medical decisions."
  };
}

/**
 * Generates executive summary based on overall results
 */
function generateExecutiveSummary(testName, normal, high, low, critical, total) {
  let summary = `Your ${testName} test has been completed. `;
  
  if (critical > 0) {
    summary += `⚠️ IMPORTANT: ${critical} parameter(s) show critical values that require immediate medical attention. `;
  } else if (high > 0 || low > 0) {
    summary += `${high + low} parameter(s) are outside the normal range and may need attention. `;
  } else {
    summary += `All ${total} parameters are within normal ranges. `;
  }
  
  summary += "Please review the detailed explanation below and discuss with your doctor.";
  
  return summary;
}

/**
 * Explains individual parameter in layman's terms
 */
function explainParameter(param, testType) {
  const { name, value, unit, normalRange, status } = param;
  
  // Get layman explanation for common parameters
  const explanation = getParameterExplanation(name, testType);
  
  // Status interpretation
  let statusText = "";
  let icon = "";
  
  switch (status) {
    case "Normal":
      statusText = "This is within the healthy range.";
      icon = "✓";
      break;
    case "High":
      statusText = "This is higher than the normal range.";
      icon = "↑";
      break;
    case "Low":
      statusText = "This is lower than the normal range.";
      icon = "↓";
      break;
    case "Critical":
      statusText = "⚠️ This requires immediate medical attention.";
      icon = "⚠️";
      break;
  }
  
  return {
    parameter: name,
    value: `${value} ${unit}`,
    normalRange: normalRange,
    status: status,
    icon: icon,
    whatItMeans: explanation,
    interpretation: statusText
  };
}

